    // or not at all.
    tx(() => {
      run("UPDATE cash_ledger SET amount=?, description=?, date=? WHERE id=?",
        [amount, body.description !== undefined ? body.description : existing.description, paymentDate, params.id]);
      rebuildCashAccountBalance(existing.cash_account_id);
    });
    addAudit(user, "Cash ledger entry updated", existing.reference_number || existing.id);
