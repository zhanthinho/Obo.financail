// physical cash), fully separate from the customer-facing `clients` /
// `account_ledger` / `transfers` / `exchange_transactions` tables (see the
// design note at the top of schema.sql's cash_accounts block). Nothing in
// this file ever reads or writes clients.balance_usd/balance_slsh or
// account_ledger — Cash in Hand is 100% additive, by design, per the
// explicit "do not touch existing business logic" requirement.
