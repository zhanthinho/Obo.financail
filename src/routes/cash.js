class CashMutationError extends Error {
  constructor(status, message) { super(message); this.status = status; }
}

// Ledger rows generated by a Transfer/Exchange/Loan/Loan-repayment are
// tagged with a source_type and must only ever be edited/deleted through
// that feature's own endpoint — mirrors routes/ledger.js's rejectIfLinked
// for account_ledger exactly, applied here to cash_ledger.
const LINKED_SOURCE_TYPES = {
  cash_transfer: "its Cash Transfer record",
  cash_exchange: "its Cash Exchange record",
  loan: "its Loan record",
  loan_repayment: "its Loan record",
  // PAYMENT / CASH IN HAND INTEGRATION round: the cash-side leg a customer
  // Deposit/Withdrawal creates (see routes/accounts.js's ledgerMove) is
  // edited/deleted only through that Payment itself (PATCH/DELETE
  // /api/account-ledger/:id), which keeps this leg in sync automatically —
  // never directly from the Cash Movements tab.
  customer_payment: "the originating Payment",
  // EXCHANGE WORKSPACE round: the two Cash in Hand legs a client Money
  // Exchange optionally creates (Cash Out From / Cash In To — see
  // routes/transactions.js) are edited/deleted only through that Exchange
  // itself, exactly like a Payment's cash leg just above.
  exchange: "its Exchange record",
  // COMPANY EXPENSES round: an expense's withdrawal (and the reversal posted
  // when it is cancelled) is changed only through Company Expenses, which
  // keeps the expense and its cash movement in step.
  expense: "its Company Expense record",
  expense_reversal: "its Company Expense record",
};
function rejectIfLinked(res, entry) {
  const moduleName = entry.source_type && LINKED_SOURCE_TYPES[entry.source_type];
  if (moduleName) {
    badRequest(res, `This entry is part of ${moduleName} — edit or delete it from there instead.`);
    return true;
  }
  return false;
}

function accountToJSON(a) {
  return {
    id: a.id, name: a.name, type: a.type, currency: a.currency, balance: a.balance,
    status: a.status, reference: a.reference, notes: a.notes,
    lastActivityAt: a.last_activity_at, createdAt: a.created_at, createdBy: a.created_by,
    deactivatedAt: a.deactivated_at, deactivatedBy: a.deactivated_by, deactivationReason: a.deactivation_reason,
  };
}
function accountBasic(id) {
  if (!id) return null;
  const a = get("SELECT id, name, type, currency, status FROM cash_accounts WHERE id = ?", [id]);
  return a ? { id: a.id, name: a.name, type: a.type, currency: a.currency, status: a.status } : null;
}
function ledgerToJSON(e) {
  return {
    id: e.id, cashAccountId: e.cash_account_id, cashAccount: accountBasic(e.cash_account_id),
    type: e.type, currency: e.currency, amount: e.amount, balanceAfter: e.balance_after,
    description: e.description, referenceNumber: e.reference_number, reference: e.reference,
    counterpartyClientId: e.counterparty_client_id, counterpartyLabel: e.counterparty_label,
    staffId: e.staff_id, staffName: e.staff_name, date: e.date, createdAt: e.created_at,
    sourceType: e.source_type, sourceId: e.source_id, editable: !e.source_type,
    // Lets the Cash Movements tab offer a "View Payment" link back to the
    // originating customer Deposit/Withdrawal (spec's "transaction linking"
    // requirement) — null for every other kind of cash movement.
    paymentLedgerId: e.source_type === "customer_payment" ? e.source_id : null,
  };
}

// PAYMENT / CASH IN HAND INTEGRATION round ---------------------------------
// Shared by routes/accounts.js's ledgerMove (POST .../deposit|withdraw) and
// routes/ledger.js's PATCH/DELETE — the exact same validation and
// insert/update/delete logic a Payment needs to keep its mirrored Cash in
// Hand leg correct, kept here (next to cash_accounts' own rules) instead of
// duplicated in two different route files.

// Validates a customer Payment's chosen Cash in Hand source/destination
// before anything is written. `type` is the customer-side ledger type
// ("deposit"/"withdrawal") — mirrored 1:1 onto the cash leg (a customer
// deposit means cash physically came IN; a customer withdrawal means cash
// physically went OUT). CASH IN HAND NEGATIVE BALANCE round: this used to
// also block a withdrawal that would take the account negative; that check
// is gone (see below), so `amount`/`excludeCashLedgerId` are kept only for
// callers that still pass them and are otherwise unused here now.
function validatePaymentCashAccount(cashAccountId, currency, type, amount, excludeCashLedgerId) {
  if (!cashAccountId) return { cashAccount: null };
  const a = get("SELECT * FROM cash_accounts WHERE id = ?", [cashAccountId]);
  if (!a) return { error: "Selected Cash Account was not found." };
  if (a.status !== "active") return { error: `${a.name} is deactivated — choose another Cash Account.` };
  if (a.currency !== currency) return { error: `Cash Account currency mismatch — ${a.name} is ${a.currency}, this payment is ${currency}.` };
  // CASH IN HAND NEGATIVE BALANCE round: a Payment's cash leg may now take a
  // Cash in Hand account negative on withdrawal, same as every other Cash in
  // Hand withdrawal-style move (see routes/cash.js's withdraw/transfer/
  // exchange routes) and matching the customer-accounts debt policy.
  return { cashAccount: a };
}

// True when at least one active Cash in Hand account exists for this
// currency — used to decide whether a Payment must name one at all (an
// installation with no Cash in Hand accounts configured yet behaves exactly
// as before this round).
function hasActiveCashAccountsFor(currency) {
  return (get("SELECT COUNT(*) as n FROM cash_accounts WHERE currency = ? AND status = 'active'", [currency])?.n || 0) > 0;
}

// Inserts the cash-side leg of a customer Payment and rebuilds that cash
// account's balance. Returns the new cash_ledger row's id.
function postPaymentCashLeg({ cashAccount, type, amount, date, createdAt, staffId, staffName, reference, counterpartyClientId, counterpartyLabel, description, sourceId }) {
  const id = uid("csl");
  const refNum = nextCashLedgerReference(type);
  run(
    "INSERT INTO cash_ledger (id, cash_account_id, type, currency, amount, balance_after, description, reference_number, reference, counterparty_client_id, counterparty_label, staff_id, staff_name, date, created_at, source_type, source_id) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
    [id, cashAccount.id, type, cashAccount.currency, amount, 0, description, refNum, reference || null, counterpartyClientId || null, counterpartyLabel || null, staffId, staffName, date, createdAt, "customer_payment", sourceId]
  );
  rebuildCashAccountBalance(cashAccount.id);
  return id;
}

// Finds the cash_ledger leg a given Payment (account_ledger row) created, if
// any — used by the Payment's own edit/delete to keep it synchronized.
function findPaymentCashLeg(paymentLedgerId) {
  return get("SELECT * FROM cash_ledger WHERE source_type = 'customer_payment' AND source_id = ?", [paymentLedgerId]);
}

// Removes a Payment's linked cash leg (on Payment delete) and rebuilds that
// cash account's balance. Safe to call even if no leg exists.
function removePaymentCashLeg(paymentLedgerId) {
  const row = findPaymentCashLeg(paymentLedgerId);
  if (!row) return null;
  run("DELETE FROM cash_ledger WHERE id = ?", [row.id]);
  rebuildCashAccountBalance(row.cash_account_id);
  return row;
}
