  // ---------------------------------------------------------------------
  // Cash Ledger — "Recent Cash Movements" (every deposit/withdrawal across
  // every cash account, including the legs transfers/exchanges/loans post)
  // ---------------------------------------------------------------------
  router.get("/api/cash/ledger", (req, res, params, query) => {
    const user = requireAuth(req, res); if (!user) return;
    if (!requirePerm(user, res, "cash.view")) return;
    const clauses = [], p = [];
    if (query.cashAccountId) { clauses.push("cash_account_id = ?"); p.push(query.cashAccountId); }
    if (query.currency && query.currency !== "all") { clauses.push("currency = ?"); p.push(query.currency); }
    if (query.type && query.type !== "all") { clauses.push("type = ?"); p.push(query.type); }
    if (query.search) { clauses.push("(description LIKE ? OR reference_number LIKE ? OR counterparty_label LIKE ?)"); p.push(`%${query.search}%`, `%${query.search}%`, `%${query.search}%`); }
    if (query.from) { clauses.push("date(date) >= date(?)"); p.push(query.from); }
    if (query.to) { clauses.push("date(date) <= date(?)"); p.push(query.to); }
    // CASH ACCOUNT VIEW round: two additive filters for the per-account Cash
    // Movements tab's filter bar (Staff, Reference) — same plain-equality/
    // LIKE pattern as every other filter here, nothing existing changes when
    // these params are absent.
    if (query.staffId) { clauses.push("staff_id = ?"); p.push(query.staffId); }
    if (query.reference) { clauses.push("(reference_number LIKE ? OR reference LIKE ?)"); p.push(`%${query.reference}%`, `%${query.reference}%`); }
    const where = clauses.length ? "WHERE " + clauses.join(" AND ") : "";
    // CASH ACCOUNT VIEW round: `id DESC` added as a final, explicit tiebreaker
    // for rows that share the exact same date and created_at (spec section
    // 5's "unique transaction id as tie-breaker for equal timestamps") — a
    // purely additive, deterministic refinement of the existing newest-first
    // order; it never changes the relative order of any two rows that don't
    // already tie on both date and created_at.
    const rows = all(`SELECT * FROM cash_ledger ${where} ORDER BY date DESC, created_at DESC, id DESC`, p);
    newestFirst(rows);
    sendJSON(res, 200, { entries: rows.map(ledgerToJSON) });
  });

